/** Pinta una rejilla de dígitos en un canvas, un píxel por celda (se escala con CSS). */
export function paintGrid(cv: HTMLCanvasElement, g: readonly string[]) {
  cv.width = g[0].length;
  cv.height = g.length;
  const x = cv.getContext('2d')!;
  x.clearRect(0, 0, cv.width, cv.height);
  g.forEach((r, y) =>
    [...r].forEach((ch, i) => {
      if (ch === '.') return;
      x.fillStyle = HEX[+ch];
      x.fillRect(i, y, 1, 1);
    }),
  );
}

const BAYER = [0, 8, 2, 10, 12, 4, 14, 6, 3, 11, 1, 9, 15, 7, 13, 5].map((v) => (v + 0.5) / 16);

/** Trama ordenada (Bayer 4×4) de un campo de luminancias 0 → 1 a la rampa de fósforo. */
export function dither(img: ImageData, lum: (x: number, y: number) => number) {
  const { width: W, height: H, data } = img;
  for (let y = 0; y < H; y++)
    for (let x = 0; x < W; x++) {
      const l = Math.max(0, Math.min(1, lum(x, y))) * 5;
      const c = RAMP[Math.min(5, Math.floor(l + BAYER[(y & 3) * 4 + (x & 3)]))];
      const o = (y * W + x) * 4;
      data[o] = c[0];
      data[o + 1] = c[1];
      data[o + 2] = c[2];
      data[o + 3] = 255;
    }
  return img;
}
